def fmt_date(s):
    import datetime
    d = datetime.date.fromisoformat(s)
    return f"{DAYS[d.weekday()]} {d.day} {MONTHS[d.month - 1]}"


def fence(text):
    return "```markdown\n" + text.strip() + "\n```"


